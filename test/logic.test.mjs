import { normalize, isUsed, allMatch, makeCode } from '../src/logic.js';
import assert from 'node:assert/strict';
const eq = (a, b) => assert.equal(normalize(a), normalize(b), `${a} vs ${b}`);
const ne = (a, b) => assert.notEqual(normalize(a), normalize(b), `${a} vs ${b}`);
eq('Border', 'border'); eq('Borders', 'border'); eq('  the border ', 'Border'); eq('Border!', 'border');
eq('Cherries', 'cherry'); eq('boxes', 'box'); eq('Mexico', 'mexico'); eq('Tennessee', 'tennessee');
eq('Ice  Cream', 'ice cream'); eq('Café', 'cafe');
ne('Adam', 'Adam & Eve'); ne('bus', 'bu'); ne('glass', 'glas');
assert.equal(normalize('Texas'), 'texa'); // known quirk, both sides normalize the same way so matching still works
eq('Texas', 'texas');
assert.ok(isUsed('Avocados', ['avocado']));
assert.ok(!isUsed('Florida', ['avocado']));
assert.ok(allMatch([{ norm: 'border' }, { norm: 'border' }]));
assert.ok(!allMatch([{ norm: 'border' }, { norm: 'wall' }]));
assert.ok(!allMatch([{ norm: 'border' }]));
assert.match(makeCode(), /^[A-HJ-NP-Z]{4}$/);
console.log('logic tests passed');
import { isClose, nearlyMatch, commonWord } from '../src/logic.js';
assert.ok(isClose('Tennessee', 'Tennesse'));
assert.ok(isClose('Cliff', 'Cliff Swaim'));
assert.ok(!isClose('cat', 'car'));
assert.ok(!isClose('Border', 'Wall'));
assert.ok(!isClose('Adam', 'Eve'));
assert.ok(nearlyMatch(['Tennessee', 'Tennessee', 'Tennesse']));
assert.ok(nearlyMatch(['cliff', 'Cliff', 'Cliff Swaim']));
assert.ok(!nearlyMatch(['Border', 'Border', 'Wall']));
assert.ok(!nearlyMatch(['Fence', 'fences']), 'exact match is a win, not a near match');
assert.equal(commonWord(['Tennessee', 'Tennesse', 'Tennessee']), 'Tennessee');
console.log('close-match tests passed');
eq('running', 'run'); eq('Baked', 'bake'); eq('baking', 'bake'); eq('jumped', 'jump'); eq('played', 'play');
eq('hoping', 'hope'); eq('hopping', 'hop'); eq('wedding', 'wed'); eq('Fishing', 'fish'); eq('falling', 'fall');
ne('hoping', 'hop'); ne('king', 'k'); ne('red', 'r'); ne('bleed', 'ble'); ne('string', 'str'); ne('cat', 'car');
eq('Bumbershoot', 'bumbershoots'); eq('Fence', 'fences');
console.log('word-ending tests passed');
